/**
 * Пример выписки для кнопки «Попробовать на примере»: CSV «как у банка» —
 * разделитель «;», дата «ДД.ММ.ГГГГ ЧЧ:ММ», сумма с запятой и минусом,
 * лишние колонки (статус, валюта). Даты — последние три недели от сегодня.
 */
const ROWS: [daysAgo: number, amount: string, description: string][] = [
  [1, '-486,90', 'ПЯТЕРОЧКА 4512 МОСКВА'],
  [1, '-189,00', 'COFFEE LIKE'],
  [2, '-126,00', 'МЕТРО МОСКВА'],
  [3, '-2 340,00', 'ВКУСВИЛЛ'],
  [4, '-649,00', 'КИНО ОКТЯБРЬ БИЛЕТЫ'],
  [5, '-399,00', 'Подписка на музыку'],
  [6, '-1 120,50', 'Шоколадница'],
  [7, '12 000,00', 'Перевод от ИП Смирнов за лендинг'],
  [8, '-312,00', 'АПТЕКА 36,6'],
  [9, '-78,00', 'Самокат'],
  [10, '-4 990,00', 'Кроссовки, магазин обуви'],
  [12, '-890,00', 'Мобильная связь'],
  [14, '-1 560,00', 'ПЕРЕКРЕСТОК'],
  [16, '-450,00', 'Такси'],
  [18, '-31,02', 'Непонятный платёж'],
  [20, '1 240,17', 'Кешбэк за месяц'],
]

const pad = (n: number) => String(n).padStart(2, '0')

export function makeSampleCsv(now = new Date()): string {
  const lines = ['Дата операции;Статус;Сумма операции;Валюта;Описание']
  for (const [daysAgo, amount, description] of ROWS) {
    const d = new Date(now)
    d.setDate(d.getDate() - daysAgo)
    const date = `${pad(d.getDate())}.${pad(d.getMonth() + 1)}.${d.getFullYear()} ${pad(9 + (daysAgo % 12))}:${pad((daysAgo * 7) % 60)}`
    lines.push(`${date};OK;${amount};RUB;${description}`)
  }
  // Строка с ошибкой: её нельзя импортировать, мастер это покажет.
  lines.push('вчера;OK;-100,00;RUB;Дата словами')
  return lines.join('\n')
}
